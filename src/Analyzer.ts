
type MqttPacket = {
    clientId: string
    topic: string
    payload: string
}

type MultiType = MultiTypeAtomic | MultiTypeArray | MultiTypeRecord

type MultiTypeDefinition = MultiType[]

type MultiTypeAtomic = {
    type: undefined | string | number | boolean
}

type MultiTypeArray = {
    type: 'array'
    items: MultiTypeDefinition
}

interface MultiTypeRecord {
    type: 'record'
    properties: Record<string, MultiTypeDefinition>
}

type AnalyzeResults = Record<string, {packetCount: number, definition: MultiTypeDefinition}>


export default class Analyzer {


    private payloadsPerTopic = new Map<string, any[]>

    addPacket(packet: MqttPacket){
        let payload
        try {
            payload = JSON.parse(packet.payload)
        } catch (err){
            console.warn('skipping packet, failed to parse payload for packet', packet.payload, err)
            return
        }


        if(!this.payloadsPerTopic.has(packet.topic)){
            this.payloadsPerTopic.set(packet.topic, [])
        }

        this.payloadsPerTopic.get(packet.topic).push(payload)
    }

    analyzeAndGenerateTypescriptTypes(convertTopicToTypeName: (topic: string)=>string){
        return this.generateTypescriptTypes(convertTopicToTypeName, this.analyzePackets())
    }

    private analyzePackets(){
        console.log('analyzing packets ...')
        const result: AnalyzeResults = {}

        for(const entry of this.payloadsPerTopic){
            const topic = entry[0]

            const payloads = entry[1]

            console.log('  topic', topic, payloads.length, 'packets')

            const typeDefinition = this.getTypeDefinitionForMultipleValues(payloads)

            result[topic] = {
                packetCount: payloads.length,
                definition: typeDefinition
            }
        }

        console.log('  done')
        return result
    }

    private generateTypescriptTypes(convertTopicToTypeName: (topic: string)=>string, analyzeResults: AnalyzeResults){
        console.log('generating typescript types ...')
        let str = ''

        for(const topic of Object.keys(analyzeResults)){
            const result = analyzeResults[topic]

            const typeName = convertTopicToTypeName(topic)

            try {
                const typescriptType = this.makeTypescriptType(result.definition)

                str += `/* automatically generated by analyzing ${result.packetCount} packets */\nexport type ${typeName} = ${typescriptType}\n\n`
            } catch (err){
                console.error('failed to makeTypescriptType for topic', topic, JSON.stringify(result.definition, null, 2))
                throw err
            }
        }

        console.log('  done')
        return str
    }

    private makeTypescriptType(typeDefinition: MultiTypeDefinition | MultiType, indent?: string, isWrappedWithArray?: boolean): string{

        if(typeof indent !== 'string'){
            indent = ''
        }

        if(typeDefinition instanceof Array){
            if(typeDefinition.length === 0){
                return 'unknown'
            } else if(typeDefinition.length === 1){
                return this.makeTypescriptType(typeDefinition[0], indent, isWrappedWithArray)
            } else {

                // check if the type of all entries is the same type (e.g. all are numbers)
                let hasCommonType = true
                let commonType = typeof typeDefinition[0].type

                for(const t of typeDefinition){
                    let type = typeof t.type

                    if(type !== 'string' && type !== 'number' && type !== 'boolean'){
                        hasCommonType = false
                        break
                    }

                    if(type !== commonType){
                        hasCommonType = false
                        break
                    }
                }

                if(hasCommonType && typeDefinition.length > 10){
                    return commonType
                } else {
                    return indent + (isWrappedWithArray ? '(' : '') + typeDefinition.map(m => this.makeTypescriptType(m, indent + '  ').trim()).join(' | ') + (isWrappedWithArray ? ')' : '')
                }
            }
        } else {

            //@ts-ignore
            if(typeDefinition.items){
                return this.makeTypescriptType((typeDefinition as MultiTypeArray).items, indent, true) + '[]'
            }

            //@ts-ignore
            if(typeDefinition.properties){
                let str = indent + '{\n'

                for(const key of Object.keys((typeDefinition as MultiTypeRecord).properties)){
                    const s = this.makeTypescriptType((typeDefinition as MultiTypeRecord).properties[key], indent + '  ')

                    const encapsulateWithLiterals = key.substring(0, 1).match(/^\d$/) || key.match(/[^a-zA-Z0-9_]/)
                    str += indent + '  ' + (encapsulateWithLiterals ? `"${key}"` : key) + ': ' + s.trim() + '\n'
                }

                return str + indent + '}'
            }

            return indent + (typeof typeDefinition.type === 'string' ? `'${typeDefinition.type}'` : typeDefinition.type)
        }
    }

    private tuneTypeDefinition(typeDefinition: MultiTypeDefinition, additionalTypeDefinition: MultiType){


        let typeAlreadyExists = false

        for(const type of typeDefinition){
            if(type.type === additionalTypeDefinition.type){
                typeAlreadyExists = true

                // tune types array and record (others can not be tuned)

                //@ts-ignore
                if(additionalTypeDefinition.items){

                    this.tuneTypeDefinitionWithMultiple((type as MultiTypeArray).items, (additionalTypeDefinition as MultiTypeArray).items)
                }

                //@ts-ignore
                if(additionalTypeDefinition.properties){

                    for(const key of Object.keys((additionalTypeDefinition as MultiTypeRecord).properties)){
                        if(!(type as MultiTypeRecord).properties[key]){
                            (type as MultiTypeRecord).properties[key] = (additionalTypeDefinition as MultiTypeRecord).properties[key]
                        } else {
                            this.tuneTypeDefinitionWithMultiple((type as MultiTypeRecord).properties[key], (additionalTypeDefinition as MultiTypeRecord).properties[key])
                        }
                    }
                }

            }
        }


        if(!typeAlreadyExists){
            typeDefinition.push(additionalTypeDefinition)
        }
    }

    private tuneTypeDefinitionWithMultiple(typeDefinition: MultiTypeDefinition, additionalTypeDefinitions: MultiType[]){
        for(const a of additionalTypeDefinitions){
            this.tuneTypeDefinition(typeDefinition, a)
        }
    }

    private getTypeDefinitionForMultipleValues(data: any[]){
        const typeDefinition: MultiTypeDefinition = []

        for(const d of data){
            this.tuneTypeDefinitionWithMultiple(typeDefinition, this.getTypeDefinition(d))
        }

        return typeDefinition
    }

    private getTypeDefinition(data: any): MultiTypeDefinition {

        const typeOfData = typeof data

        switch(typeOfData){
            case 'undefined':
            case 'string':
            case 'number':
            case 'boolean': return [{type: data}]

            case 'object': {
                if(data instanceof Array){
                    const possibleTypes: MultiTypeDefinition = []


                    for(const d of data){
                        const type = this.getTypeDefinition(d)

                        for(const t of type){
                            this.tuneTypeDefinition(possibleTypes, t)
                        }
                    }

                    return [{
                        type: 'array',
                        items: possibleTypes
                    }]

                } else {// Key:Value Object
                    const ret: MultiTypeRecord = {
                        type: 'record',
                        properties: {}
                    }

                    for(const key of Object.keys(data)){
                        ret.properties[key] = this.getTypeDefinition(data[key])
                    }

                    return [ret]
                }
            }

        }

        throw new Error('unsupported type: ' + typeOfData)
    }

}